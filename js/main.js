const isChromium = navigator.userAgentData?.brands?.some((b) => b.brand === "Chromium");

function lensMap(w, h, r) {
  const c = document.createElement("canvas");
  c.width = w; c.height = h;
  const ctx = c.getContext("2d");
  const img = ctx.createImageData(w, h);
  const bezel = Math.min(18, Math.min(w, h) * 0.35);
  const hw = w / 2, hh = h / 2;
  r = Math.min(r, hw, hh);

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const px = x + 0.5 - hw, py = y + 0.5 - hh;
      const qx = Math.abs(px) - (hw - r), qy = Math.abs(py) - (hh - r);
      let nx, ny, dist;
      if (qx > 0 && qy > 0) {
        const len = Math.hypot(qx, qy);
        dist = r - len;
        nx = (qx / len) * Math.sign(px); ny = (qy / len) * Math.sign(py);
      } else if (qx > qy) {
        dist = r - qx; nx = Math.sign(px); ny = 0;
      } else {
        dist = r - qy; nx = 0; ny = Math.sign(py);
      }
      const t = Math.max(0, Math.min(1, dist / bezel));
      const k = (1 - t) ** 2;
      const i = (y * w + x) * 4;
      img.data[i] = 128 - nx * k * 127;
      img.data[i + 1] = 128 - ny * k * 127;
      img.data[i + 2] = 128;
      img.data[i + 3] = 255;
    }
  }
  ctx.putImageData(img, 0, 0);
  return c.toDataURL();
}

if (isChromium) {
  document.documentElement.classList.add("lens");
  const defs = $("#lens-defs");
  const NS = "http://www.w3.org/2000/svg";
  let n = 0;

  const build = (el) => {
    const { width, height } = el.getBoundingClientRect();
    const w = Math.round(width), h = Math.round(height);
    if (!w || !h || (el._lens && el._lens.w === w && el._lens.h === h)) return;
    const r = parseFloat(getComputedStyle(el).borderTopLeftRadius) || 0;
    const id = el._lens?.id || `lens-${n++}`;
    defs.querySelector(`#${id}`)?.remove();

    const filter = document.createElementNS(NS, "filter");
    filter.id = id;
    filter.setAttribute("x", 0); filter.setAttribute("y", 0);
    filter.setAttribute("width", w); filter.setAttribute("height", h);
    filter.setAttribute("filterUnits", "userSpaceOnUse");
    filter.setAttribute("color-interpolation-filters", "sRGB");
    filter.innerHTML = `
      <feGaussianBlur in="SourceGraphic" stdDeviation="3" result="blur"/>
      <feImage href="${lensMap(w, h, r)}" x="0" y="0" width="${w}" height="${h}" result="map" preserveAspectRatio="none"/>
      <feDisplacementMap in="blur" in2="map" scale="${Math.min(48, h * 0.7)}" xChannelSelector="R" yChannelSelector="G"/>`;
    defs.appendChild(filter);
    el._lens = { id, w, h };
    el.style.setProperty("--lens", `url(#${id})`);
  };

  const ro = new ResizeObserver((entries) => entries.forEach((en) => build(en.target)));
  document.querySelectorAll("[data-lens]").forEach((el) => ro.observe(el));
}

