// ---------- Video player (thumbnail bosilganda iframe yuklanadi) ----------

let activePlayer = null;

function resetPlayer(player) {
  const iframe = player.querySelector("iframe");
  if (iframe) iframe.remove();
  player.classList.remove("playing");
  if (activePlayer === player) activePlayer = null;
}

function play(player) {
  if (activePlayer && activePlayer !== player) resetPlayer(activePlayer);
  if (player.querySelector("iframe")) return;
  const iframe = document.createElement("iframe");
  iframe.src = `https://www.youtube-nocookie.com/embed/${player.dataset.id}?autoplay=1&rel=0&playsinline=1&hl=${lang}`;
  iframe.title = player.getAttribute("aria-label");
  iframe.allow = "autoplay; encrypted-media; picture-in-picture; fullscreen";
  iframe.allowFullscreen = true;
  player.appendChild(iframe);
  player.classList.add("playing");
  activePlayer = player;
}

document.addEventListener("click", (e) => {
  const player = e.target.closest(".player");
  if (player) play(player);
});
document.addEventListener("keydown", (e) => {
  const player = e.target.closest?.(".player");
  if (player && (e.key === "Enter" || e.key === " ")) { e.preventDefault(); play(player); }
});

